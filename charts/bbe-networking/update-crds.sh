#!/usr/bin/env bash
# Writes the CRDs of MetalLB and cert-manager into crds/, at the versions Chart.yaml depends on. Run it after changing
# either version.
#
# Helm installs a chart's crds/ folder before anything else, and refreshes the kinds it knows afterwards. CRDs the
# subcharts create from their templates are only known to Helm from its next run, so the hooks creating MetalLB's
# address pools and cert-manager's certificates failed on a first install. bbe applies crds/ before every install and
# upgrade, which keeps them current.
#
# The CRDs are marked `helm.sh/resource-policy: keep`. Releases from before this moved them kept MetalLB's in their
# templates, and Helm would delete them on upgrading, with every address pool, if the CRDs bbe applies first didn't
# say to keep them. MetalLB's conversion webhook names its service in the bbe-networking namespace, where bbe installs
# the package, and its placeholder caBundle is left out, as MetalLB's controller sets it.
set -euo pipefail
cd "$(dirname "$0")"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

version() {
  NAME="$1" yq '.dependencies[] | select(.name == env(NAME)) | .version' Chart.yaml
}

# Labels naming a release don't apply to CRDs outside any release
tidy='
  .metadata.annotations["helm.sh/resource-policy"] = "keep"
  | del(.metadata.labels["helm.sh/chart"])
  | del(.metadata.labels["app.kubernetes.io/managed-by"])
  | del(.metadata.labels["app.kubernetes.io/instance"])
  | del(.spec.conversion.webhook.clientConfig.caBundle)
'

metallb=$(version metallb)
helm pull metallb --repo https://metallb.github.io/metallb --version "$metallb" --untar --destination "$work"
{
  echo "# Generated by update-crds.sh from the metallb chart ${metallb}, don't edit"
  helm template bbe-networking "$work/metallb" --namespace bbe-networking \
    | yq "select(.kind == \"CustomResourceDefinition\") | ${tidy}"
} > crds/metallb.yaml

certmanager=$(version cert-manager)
helm pull cert-manager --repo https://charts.jetstack.io --version "$certmanager" --untar --destination "$work"
{
  echo "# Generated by update-crds.sh from the cert-manager chart ${certmanager}, don't edit"
  helm template bbe-networking "$work/cert-manager" --namespace bbe-networking --set crds.enabled=true \
    | yq "select(.kind == \"CustomResourceDefinition\") | ${tidy}"
} > crds/cert-manager.yaml

echo "Wrote crds/metallb.yaml ($(grep -c '^kind: CustomResourceDefinition' crds/metallb.yaml) CRDs) and crds/cert-manager.yaml ($(grep -c '^kind: CustomResourceDefinition' crds/cert-manager.yaml) CRDs)"
